import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8').replace(/^\uFEFF/,''));
export function generateCatalog(){
 const input=read('catalog/books.json'),overrides=read('catalog/overrides.json'),policy=read('catalog/download-policy.json');
 const legacyDownloads=new Set(policy.legacyDownloadIds),restricted=new Set(policy.restrictedIds);
 const manifests=fs.readdirSync(path.join(root,'catalog')).filter(f=>f.endsWith('.catalog.json')).sort();
 let books=[...input.books],categories=[...input.categories];
 for(const name of manifests){const source=read('catalog/'+name);books.push(...(source.books||[]));categories.push(...(source.categories||[]));}
 const known=new Set(books.map(b=>b.file));
 const walk=dir=>fs.existsSync(dir)?fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]):[];
 for(const file of walk(path.join(root,'assets/books')).filter(f=>/\.pdf$/i.test(f))){
  const relative=path.relative(path.join(root,'assets/books'),file).split(path.sep).join('/');
  const existing=books.find(b=>b.file===relative);
  const permission={...existing,...overrides[existing?.id]}.rights;
  if(existing && !(permission?.redistribution==='verified'&&permission.evidence))throw Error('PDF on disk requires redistribution evidence: '+relative);
  if(!known.has(relative))books.push({id:'book-'+createHash('sha256').update(relative).digest('hex').slice(0,16),file:relative,titleAr:path.basename(relative,'.pdf'),titleEn:'',author:'',category:'uncategorized',source:'included',rights:{redistribution:'unverified',evidence:''}});
 }
 if(books.some(b=>b.category==='uncategorized')&&!categories.some(c=>c.id==='uncategorized'))categories.push({id:'uncategorized',ar:'غير مصنف',en:'Uncategorized'});
 const ids=new Set(),categoryIds=new Set(categories.map(c=>c.id));
 books=books.map(original=>{
  const b={...original,...overrides[original.id]};
  if(!/^[a-zA-Z0-9_-]+$/.test(b.id)||ids.has(b.id))throw Error('Invalid or duplicate catalog ID: '+b.id);ids.add(b.id);
  if(!categoryIds.has(b.category))throw Error('Unknown category for '+b.id);
  if(b.file&&(b.file.startsWith('/')||/^[a-zA-Z]:/.test(b.file)||b.file.split('/').some(p=>p==='..'||p==='.'||p.includes('\\'))))throw Error('Unsafe book path: '+b.id);
  if(b.officialUrl&&!/^https:\/\//.test(b.officialUrl))throw Error('Official source must use HTTPS: '+b.id);
  const verified=b.rights?.redistribution==='verified'&&!!b.rights.evidence;
  if(b.source==='included'&&!verified)throw Error('Included PDF requires redistribution evidence: '+b.id);
  const legacyDownload=b.source==='legacy'&&legacyDownloads.has(b.id);
  return {...b,downloadAllowed:!restricted.has(b.id)&&(verified||legacyDownload),source:b.source||'external'};
 });
 return {version:1,categories,books};
}
const catalog=generateCatalog();
const output="'use strict';\n/* Generated by tools/build-book-catalog.mjs. Edit catalog manifests instead. */\nconst BOOK_CATEGORIES = "+JSON.stringify(catalog.categories,null,2)+';\nconst BOOKS = '+JSON.stringify(catalog.books,null,2)+';\n';
const target=path.join(root,'js/books-data.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==output)throw Error('Catalog output is stale. Run node tools/build-book-catalog.mjs');}
else fs.writeFileSync(target,output);
console.log(JSON.stringify({books:catalog.books.length,availableDownloads:catalog.books.filter(b=>b.downloadAllowed).length}));
